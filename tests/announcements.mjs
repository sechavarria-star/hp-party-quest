import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createBackend } from './security-regression.mjs';
const { context, tables, call } = createBackend();
const photo = 'data:image/jpeg;base64,' + fs.readFileSync(new URL('./fixtures/selfie-qa.jpg', import.meta.url)).toString('base64');
const register = (firstName, lastName, email) => call('register', { firstName, lastName, email, termsAccepted: true, selfieDataUrl: photo, selfieConsent: true });
const julieta = register('Julieta', 'Berlin', 'qa.announcement.julieta@hp.com');
const sebastian = register('Sebastián', 'Echavarria', 'qa.announcement.sebastian@hp.com');
const alex = register('Alex', 'QA', 'qa.announcement.alex@hp.com');
for (const voter of [sebastian, alex]) call('vote', { sessionToken: voter.sessionToken, candidateQrToken: julieta.participant.qrToken, challengeId: 'CH-COOL-GLASSES' });
const participant = tables.get('Participants')[0];
const config = context.getConfig_();
const url = context.announcementShareUrl_(participant, config);
assert.equal(context.announcementShareUrl_(participant, config), url, 'stable announcement link');
assert(!url.includes(participant.QRToken)); assert(!url.includes(participant.Email));
const token = new URL(url).searchParams.get('ganador');
const before = JSON.stringify({ participants: tables.get('Participants'), votes: tables.get('Votes'), sessions: tables.get('Sessions'), winners: tables.get('Winners') });
const announcement = call('announcement', { token });
assert.equal(announcement.greeting, '¡Felicitamos a la ganadora!');
assert.equal(announcement.fullName, 'Julieta Berlin'); assert.equal(announcement.votes, 2);
assert.equal(announcement.selfieDataUrl, photo); assert.equal(announcement.challengeName, 'Anteojos más cool');
assert.equal(context.announcementGreeting_('Sebastián'), '¡Felicitamos al ganador!');
assert.equal(context.announcementGreeting_('Alex'), '¡Felicitaciones!');
assert(!JSON.stringify(announcement).includes('@hp.com'));
assert(!JSON.stringify(announcement).includes(julieta.sessionToken));
assert.equal(JSON.stringify({ participants: tables.get('Participants'), votes: tables.get('Votes'), sessions: tables.get('Sessions'), winners: tables.get('Winners') }), before, 'opening an announcement never votes, confirms winners or creates a session');
for (const bad of ['', participant.QRToken, 'A'.repeat(90)]) assert.throws(() => call('announcement', { token: bad }), e => e.code === 'ANNOUNCEMENT_NOT_AVAILABLE');
tables.get('Challenges')[0].Status = 'CLOSED';
assert.equal(call('announcement', { token }).votes, 2, 'announcement works after voting closes');
tables.get('Winners').push({ ChallengeID: 'CH-COOL-GLASSES', ParticipantID: participant.ParticipantID, Confirmed: true, FinalVotes: 5 });
assert.equal(call('announcement', { token }).votes, 5, 'confirmed final vote count has precedence');
tables.get('Participants')[0].Status = 'INACTIVE';
assert.throws(() => call('announcement', { token }), e => e.code === 'ANNOUNCEMENT_NOT_AVAILABLE');
console.log('Announcements: public scoped link, full name/photo/votes, feminine/masculine/neutral copy, closed challenge, confirmed total, no QR/session leakage or voting side effects: OK');
