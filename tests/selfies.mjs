import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createBackend } from './security-regression.mjs';
const jpeg = fs.readFileSync(new URL('./fixtures/selfie-qa.jpg', import.meta.url));
const photo = 'data:image/jpeg;base64,' + jpeg.toString('base64');
const { call, context, tables, properties } = createBackend();
const registration = { firstName: 'Ana', lastName: 'QA', email: 'qa.selfie.ana@hp.com', termsAccepted: true };
assert.throws(() => call('register', registration), e => e.code === 'SELFIE_REQUIRED');
assert.equal(tables.get('Participants').length, 0);
assert.throws(() => call('register', { ...registration, selfieDataUrl: photo }), e => e.code === 'SELFIE_CONSENT_REQUIRED');
assert.equal(tables.get('Participants').length, 0);
assert.throws(() => context.validateSelfie_('data:image/svg+xml;base64,PHN2Zz4=', true), e => e.code === 'INVALID_SELFIE');
assert.throws(() => context.validateSelfie_('data:image/jpeg;base64,' + 'A'.repeat(200000), true), e => e.code === 'INVALID_SELFIE');
assert.throws(() => context.validateSelfie_('data:image/jpeg;base64,YWJjZA==', true), e => e.code === 'INVALID_SELFIE');
const huge = fs.readFileSync(new URL('./fixtures/selfie-too-wide.jpg', import.meta.url));
assert.throws(() => context.validateSelfie_('data:image/jpeg;base64,' + huge.toString('base64'), true), e => e.code === 'INVALID_SELFIE');
const ana = call('register', { ...registration, selfieDataUrl: photo, selfieConsent: true });
const beto = call('register', { ...registration, firstName: 'Beto', email: 'qa.selfie.beto@hp.com', selfieDataUrl: photo, selfieConsent: true });
// Simulate a participant created by the earlier optional-photo release.
tables.get('Participants')[1].SelfieUpdatedAt = '';
tables.get('Selfies').splice(1, 1);
const legacyVote = { sessionToken: beto.sessionToken, candidateQrToken: ana.participant.qrToken, challengeId: 'CH-COOL-GLASSES' };
assert.throws(() => call('vote', legacyVote), e => e.code === 'SELFIE_REQUIRED');
assert.throws(() => call('vote', { ...legacyVote, sessionToken: ana.sessionToken, candidateQrToken: beto.participant.qrToken }), e => e.code === 'CANDIDATE_SELFIE_REQUIRED');
assert.equal(ana.participant.hasSelfie, true);
assert.equal(call('session', { sessionToken: beto.sessionToken }).participant.hasSelfie, false);
assert.equal(tables.get('Selfies').length, 1);
assert.equal(context.readSelfie_(ana.participant.participantId), photo);
assert(tables.get('Selfies')[0].Data1.startsWith('b64:'));
assert.equal(call('candidate', { qrToken: ana.participant.qrToken }).selfieDataUrl, '');
assert.throws(() => call('candidate', { qrToken: ana.participant.qrToken, sessionToken: 'x'.repeat(50) }), e => e.code === 'INVALID_SESSION');
assert.equal(call('candidate', { qrToken: ana.participant.qrToken, sessionToken: beto.sessionToken }).selfieDataUrl, photo);
assert.throws(() => call('saveSelfie', { selfieDataUrl: photo, selfieConsent: true, participantId: ana.participant.participantId }), e => e.code === 'INVALID_SESSION');
const result = call('saveSelfie', { sessionToken: beto.sessionToken, participantId: ana.participant.participantId, selfieDataUrl: photo, selfieConsent: true });
assert.equal(result.participant.participantId, beto.participant.participantId);
assert.equal(tables.get('Selfies').length, 2);
assert.throws(() => call('register', { ...registration, selfieDataUrl: photo, selfieConsent: true }), e => e.code === 'EMAIL_ALREADY_REGISTERED');
assert.equal(tables.get('Selfies').length, 2);
const before = ana.participant.qrToken;
call('saveSelfie', { sessionToken: ana.sessionToken, selfieDataUrl: photo, selfieConsent: true });
assert.equal(call('session', { sessionToken: ana.sessionToken }).participant.qrToken, before);
assert.equal(tables.get('Selfies').length, 2, 'replacement does not create extra rows');
const comment = Buffer.concat([Buffer.from([255, 254, 117, 50]), Buffer.alloc(30000, 65)]);
const multiChunk = 'data:image/jpeg;base64,' + Buffer.concat([jpeg.subarray(0, 2), comment, comment, comment, jpeg.subarray(2)]).toString('base64');
call('saveSelfie', { sessionToken: ana.sessionToken, selfieDataUrl: multiChunk, selfieConsent: true });
assert.equal(context.readSelfie_(ana.participant.participantId), multiChunk, 'photo survives splitting across multiple cells');
assert(tables.get('Selfies')[0].Data3.startsWith('b64:'));
tables.get('Challenges')[0].Status = 'DRAFT';
const previous = context.getConfig_().ACTIVE_CHALLENGE_ID;
context.prepareLiveQa_();
assert.equal(context.getConfig_().ACTIVE_CHALLENGE_ID, 'CH-QA-20261120');
assert.equal(properties.get('HPQ_QA_PREVIOUS_CHALLENGE'), previous);
assert.equal(tables.get('Challenges')[0].Status, 'DRAFT', 'real challenge stays in draft');
context.prepareLiveQa_();
assert.equal(tables.get('Challenges').filter(row => row.ChallengeID === 'CH-QA-20261120').length, 1);
properties.set('HPQ_QA_EXPIRES_AT', '1');
assert.equal(context.liveQaExpired_(), true);
context.prepareLiveQa_();
assert.equal(context.getConfig_().ACTIVE_CHALLENGE_ID, previous);
assert.equal(tables.get('Challenges').find(row => row.ChallengeID === 'CH-QA-20261120').Status, 'CLOSED');
assert(properties.has('HPQ_QA_RESTORED_AT'));
console.log('Selfies: consent, JPEG/size checks, private row storage, anonymous/invalid-session denial, own-photo updates, stable QR, duplicate-email protection and QA expiry/restoration: OK');
