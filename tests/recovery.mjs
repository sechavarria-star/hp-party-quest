import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createBackend } from './security-regression.mjs';
const { context, tables, call } = createBackend();
context.MailApp = { getRemainingDailyQuota() { throw Error('Email must not be used'); }, sendEmail() { throw Error('Email must not be sent'); } };
const email = 'qa.recovery@hp.com';
const photo = 'data:image/jpeg;base64,' + fs.readFileSync(new URL('./fixtures/selfie-qa.jpg', import.meta.url)).toString('base64');
const original = call('register', { firstName: 'Ana', lastName: 'QA', email, termsAccepted: true, selfieDataUrl: photo, selfieConsent: true });
tables.get('Votes').push({ VoterParticipantID: original.participant.participantId, Valid: true });
const before = JSON.stringify({ p: tables.get('Participants'), v: tables.get('Votes'), photos: tables.get('Selfies') });
assert.throws(() => call('recover', { email: 'nobody@hp.com' }), e => e.code === 'EMAIL_NOT_REGISTERED');
assert.throws(() => call('recover', { email: '' }), e => e.code === 'INVALID_EMAIL');
assert.equal(tables.get('Sessions').length, 1);
const result = call('recover', { email: ' QA.RECOVERY@HP.COM ', participantId: 'SPOOFED' });
assert.equal(result.participant.participantId, original.participant.participantId);
assert.equal(result.participant.qrToken, original.participant.qrToken);
assert.notEqual(result.sessionToken, original.sessionToken);
assert.equal(call('session', { sessionToken: result.sessionToken }).participant.participantId, original.participant.participantId);
assert.equal(JSON.stringify({ p: tables.get('Participants'), v: tables.get('Votes'), photos: tables.get('Selfies') }), before);
const again = call('recover', { email });
assert.equal(again.participant.participantId, original.participant.participantId);
assert.equal(tables.get('Participants').length, 1);
tables.get('Participants')[0].Status = 'INACTIVE';
assert.throws(() => call('recover', { email }), e => e.code === 'EMAIL_NOT_REGISTERED');
console.log('Email-only return as requested: existing participant, stable QR/photos/votes, no email/code, repeated access, no duplicate registration, unknown/inactive account handling: OK');
