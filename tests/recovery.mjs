import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createBackend } from './security-regression.mjs';
const { context, tables, properties, call } = createBackend();
const sent = [];
context.MailApp = { getRemainingDailyQuota: () => 100, sendEmail: mail => sent.push(mail) };
const email = 'qa.recovery@hp.com';
const photo = 'data:image/jpeg;base64,' + fs.readFileSync(new URL('./fixtures/selfie-qa.jpg', import.meta.url)).toString('base64');
const registered = call('register', { firstName: 'Ana', lastName: 'QA', email, termsAccepted: true, selfieDataUrl: photo, selfieConsent: true });
tables.get('Votes').push({ VoterParticipantID: registered.participant.participantId, Valid: true });
const before = JSON.stringify({ p: tables.get('Participants'), v: tables.get('Votes'), photos: tables.get('Selfies') });
const unknown = call('requestRecovery', { email: 'not-registered@hp.com' });
assert.equal(sent.length, 0);
const issued = call('requestRecovery', { email: ' QA.RECOVERY@HP.COM ' });
assert.equal(issued.message, unknown.message);
assert.deepEqual(Object.keys(issued), Object.keys(unknown));
assert.equal(sent.length, 1); assert.equal(sent[0].to, email);
const code = sent[0].body.match(/es: (\d{6})/)[1];
assert(!JSON.stringify(issued).includes(code));
const key = 'HPQ_EMAIL_RECOVERY_' + context.sha256_(email);
assert(!properties.get(key).includes(code), 'store only the code hash');
const again = call('requestRecovery', { email });
assert.equal(sent.length, 1); assert.equal(again.recoveryId, issued.recoveryId);
assert.equal(tables.get('Sessions').length, 1, 'request does not authenticate');
const invalid = e => e.code === 'INVALID_RECOVERY';
const wrongCode = code === '000000' ? '000001' : '000000';
assert.throws(() => call('recover', { email, recoveryId: issued.recoveryId, code: wrongCode }), invalid);
assert.throws(() => call('recover', { email: 'not-registered@hp.com', recoveryId: issued.recoveryId, code }), invalid);
assert.throws(() => call('recover', { email, recoveryId: registered.participant.qrToken, code }), invalid);
const result = call('recover', { email, recoveryId: issued.recoveryId, code, participantId: 'SPOOFED' });
assert.equal(result.participant.participantId, registered.participant.participantId);
assert.equal(result.participant.qrToken, registered.participant.qrToken);
assert.notEqual(result.sessionToken, registered.sessionToken);
assert.equal(tables.get('Sessions').length, 2);
assert.equal(call('session', { sessionToken: result.sessionToken }).participant.participantId, registered.participant.participantId);
assert.equal(JSON.stringify({ p: tables.get('Participants'), v: tables.get('Votes'), photos: tables.get('Selfies') }), before);
assert.throws(() => call('recover', { email, recoveryId: issued.recoveryId, code }), invalid, 'no replay');
function expireSendWindow() { const t = JSON.parse(properties.get(key)); t.sentAt = Date.now() - 61000; properties.set(key, JSON.stringify(t)); }
expireSendWindow();
const second = call('requestRecovery', { email });
const secondCode = sent[1].body.match(/es: (\d{6})/)[1];
for (let i = 0; i < 5; i++) assert.throws(() => call('recover', { email, recoveryId: second.recoveryId, code: secondCode === '000000' ? '000001' : '000000' }), invalid);
assert.throws(() => call('recover', { email, recoveryId: second.recoveryId, code: secondCode }), invalid, 'five attempts exhaust code');
expireSendWindow();
const third = call('requestRecovery', { email });
const t = JSON.parse(properties.get(key)); t.expiresAt = Date.now() - 1; properties.set(key, JSON.stringify(t));
assert.throws(() => call('recover', { email, recoveryId: third.recoveryId, code: sent[2].body.match(/es: (\d{6})/)[1] }), invalid, 'expiry');
expireSendWindow(); call('requestRecovery', { email }); assert.equal(sent.length, 3, 'three sends per hour');
assert.throws(() => call('issueParticipantRecovery', { email }), e => e.code === 'UNKNOWN_ACTION', 'no public issuance of admin access');
const log = JSON.stringify(tables.get('AuditLog'));
assert(!log.includes(code)); assert(!log.includes(email));
const ticket = JSON.parse(properties.get(key)); ticket.windowStartedAt = 1; ticket.sentAt = 1; properties.set(key, JSON.stringify(ticket));
context.MailApp.sendEmail = () => { throw new Error('provider failure'); };
const failed = call('requestRecovery', { email });
assert.equal(failed.message, issued.message);
assert.equal(JSON.parse(properties.get(key)).used, true, 'failed delivery cannot authenticate');
console.log('Recovery: email proof, generic response, hashing, one use, expiry, attempts, resend limits, unchanged identity/QR/photos/votes and delivery failure: OK');
